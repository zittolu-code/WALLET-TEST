"""SQLAlchemy-backed ledger, soft deletions, revision log, atomic JSON backup/restore."""
import hashlib
import json
from datetime import date, datetime, timezone
from decimal import Decimal
from pathlib import Path
from sqlalchemy import create_engine, text
from sqlalchemy.engine import make_url
from ledger import calculate, LedgerError

FIELDS = ("portfolio", "ticker", "label", "kind", "trade_date", "quantity", "unit_price", "currency", "fx_eur", "fee", "notes", "broker")
SCHEMA = """
CREATE TABLE IF NOT EXISTS transactions (
 id INTEGER PRIMARY KEY, portfolio TEXT NOT NULL, ticker TEXT NOT NULL,
 label TEXT NOT NULL, kind TEXT NOT NULL, trade_date TEXT NOT NULL,
 quantity NUMERIC NOT NULL, unit_price NUMERIC NOT NULL, currency TEXT NOT NULL,
 fx_eur NUMERIC NOT NULL, fee NUMERIC NOT NULL, notes TEXT NOT NULL DEFAULT '', broker TEXT NOT NULL DEFAULT '',
 deleted INTEGER NOT NULL DEFAULT 0, created_at TEXT NOT NULL, updated_at TEXT NOT NULL
)
"""
# PostgreSQL has no auto rowid column; use explicit sequence via identity.
PG_SCHEMA = SCHEMA.replace('id INTEGER PRIMARY KEY', 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
AUDIT = """CREATE TABLE IF NOT EXISTS audit_log (
 id INTEGER PRIMARY KEY, entry_id INTEGER NOT NULL, action TEXT NOT NULL,
 previous_json TEXT, next_json TEXT, changed_at TEXT NOT NULL, actor TEXT NOT NULL
)"""
PG_AUDIT = AUDIT.replace('id INTEGER PRIMARY KEY', 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')


def engine_for(url):
    return create_engine(url, pool_pre_ping=True, future=True, connect_args={"connect_timeout": 12} if url.startswith("postgresql") else {})


TARGET_SCHEMA = """CREATE TABLE IF NOT EXISTS allocation_targets (
 portfolio TEXT NOT NULL, ticker TEXT NOT NULL, currency TEXT NOT NULL,
 broker TEXT NOT NULL DEFAULT '', target_pct NUMERIC NOT NULL,
 PRIMARY KEY (portfolio,ticker,currency,broker)
)"""


def allocation_targets(engine):
    with engine.connect() as con:
        return [dict(x) for x in con.execute(text('SELECT * FROM allocation_targets')).mappings()]


def save_target(engine, portfolio, ticker, currency, broker, target):
    value = Decimal(str(target))
    if not value.is_finite() or value < 0 or value > 100:
        raise ValueError('Obiettivo fuori dall’intervallo 0-100%.')
    params = dict(portfolio=portfolio, ticker=ticker, currency=currency, broker=broker, target_pct=str(value))
    with engine.begin() as con:
        con.execute(text('DELETE FROM allocation_targets WHERE portfolio=:portfolio AND ticker=:ticker AND currency=:currency AND broker=:broker'), params)
        con.execute(text('INSERT INTO allocation_targets (portfolio,ticker,currency,broker,target_pct) VALUES (:portfolio,:ticker,:currency,:broker,:target_pct)'), params)


def initialize(engine):
    pg = engine.dialect.name == 'postgresql'
    with engine.begin() as con:
        con.execute(text(PG_SCHEMA if pg else SCHEMA))
        con.execute(text(PG_AUDIT if pg else AUDIT))
        # Additive migration: old transactions and their audit history remain untouched.
        if pg:
            con.execute(text("ALTER TABLE transactions ADD COLUMN IF NOT EXISTS broker TEXT NOT NULL DEFAULT ''"))
        else:
            columns = {r[1] for r in con.execute(text('PRAGMA table_info(transactions)'))}
            if 'broker' not in columns:
                con.execute(text("ALTER TABLE transactions ADD COLUMN broker TEXT NOT NULL DEFAULT ''"))
        con.execute(text(TARGET_SCHEMA))


def _rows(con):
    data = con.execute(text('SELECT * FROM transactions ORDER BY trade_date,id')).mappings().all()
    return [dict(r) for r in data]


def all_transactions(engine, include_deleted=False):
    with engine.connect() as con:
        rows = _rows(con)
    return rows if include_deleted else [r for r in rows if not r['deleted']]


def _normalize(data):
    result = {k: data.get(k, '') for k in FIELDS}
    result['portfolio'] = str(result['portfolio']).strip()
    result['ticker'] = str(result['ticker']).strip().upper()
    result['label'] = str(result['label']).strip()
    result['kind'] = str(result['kind']).upper()
    result['currency'] = str(result['currency']).strip().upper()
    result['notes'] = str(result['notes']).strip()
    result['broker'] = str(result['broker'] or '').strip()
    result['trade_date'] = str(result['trade_date'])[:10]
    try:
        date.fromisoformat(result['trade_date'])
    except ValueError:
        raise LedgerError('Data operazione non valida.')
    if not result['portfolio'] or not result['ticker'] or len(result['currency']) != 3:
        raise LedgerError('Portafoglio, ticker e valuta ISO a tre lettere sono obbligatori.')
    if result['kind'] not in ('BUY', 'SELL', 'DIVIDEND'):
        raise LedgerError('Tipo di operazione non valido.')
    for k in ('quantity', 'unit_price', 'fee', 'fx_eur'):
        result[k] = str(Decimal(str(result[k])))
    if result['fx_eur'] == '0':
        raise LedgerError('Cambio non valido.')
    return result


def _audit(con, entry_id, action, before, after, actor):
    con.execute(text("""INSERT INTO audit_log (entry_id,action,previous_json,next_json,changed_at,actor)
        VALUES (:entry_id,:action,:previous_json,:next_json,:changed_at,:actor)"""),
        dict(entry_id=entry_id, action=action,
             previous_json=json.dumps(before, default=str, ensure_ascii=False) if before else None,
             next_json=json.dumps(after, default=str, ensure_ascii=False) if after else None,
             changed_at=datetime.now(timezone.utc).isoformat(), actor=actor))


def mutate(engine, action, payload=None, row_id=None, actor='owner'):
    if action not in ('add', 'edit', 'delete', 'restore'):
        raise ValueError('Operazione non supportata')
    with engine.begin() as con:
        # Serialize concurrent edits across sessions for PostgreSQL.
        if engine.dialect.name == 'postgresql':
            con.execute(text('SELECT pg_advisory_xact_lock(7142026)'))
        rows = _rows(con)
        before = next((r for r in rows if r['id'] == row_id), None)
        if action != 'add' and before is None:
            raise LedgerError('Operazione non trovata.')
        if action == 'add':
            after = {**_normalize(payload), 'deleted': 0, 'id': max([r['id'] for r in rows], default=0) + 1}
        elif action == 'edit':
            if before['deleted']:
                raise LedgerError('Ripristina prima la registrazione annullata.')
            after = {**before, **_normalize(payload)}
        else:
            after = {**before, 'deleted': 1 if action == 'delete' else 0}
        trial = [r for r in rows if r['id'] != after['id']] + [after]
        calculate(trial)  # Reject inconsistencies without modifying database.
        now = datetime.now(timezone.utc).isoformat()
        if action == 'add':
            cols = ','.join(FIELDS)
            vals = ','.join(':'+f for f in FIELDS)
            con.execute(text(f'INSERT INTO transactions (id,{cols},deleted,created_at,updated_at) VALUES (:id,{vals},0,:created_at,:updated_at)'),
                        {**after, 'created_at': now, 'updated_at': now})
        elif action == 'edit':
            sets = ','.join(f'{f}=:{f}' for f in FIELDS)
            con.execute(text(f'UPDATE transactions SET {sets}, updated_at=:updated_at WHERE id=:id'), {**after, 'updated_at': now})
        else:
            con.execute(text('UPDATE transactions SET deleted=:deleted,updated_at=:updated_at WHERE id=:id'),
                        {'id': after['id'], 'deleted': after['deleted'], 'updated_at': now})
        _audit(con, after['id'], action, before, after, actor)
        return after['id']


def audit_rows(engine):
    with engine.connect() as con:
        return [dict(r) for r in con.execute(text('SELECT id,entry_id,action,changed_at,actor FROM audit_log ORDER BY id DESC')).mappings().all()]


def export_backup(engine):
    with engine.connect() as con:
        operations = _rows(con)
        audit = [dict(r) for r in con.execute(text('SELECT * FROM audit_log ORDER BY id')).mappings().all()]
    payload = {'format': 'wallet-monitor-2', 'version': 1, 'exported_at': datetime.now(timezone.utc).isoformat(),
               'transactions': operations, 'audit_log': audit, 'allocation_targets': allocation_targets(engine)}
    serialized = json.dumps(payload, sort_keys=True, ensure_ascii=False, default=str, separators=(',', ':'))
    return json.dumps({'sha256': hashlib.sha256(serialized.encode()).hexdigest(), 'payload': payload},
                      ensure_ascii=False, default=str, indent=2).encode('utf-8')


def restore_backup(engine, content, actor='owner'):
    """Full replacement, single DB transaction; caller must create separate pre-restore backup."""
    wrapper = json.loads(content)
    payload = wrapper['payload']
    digest = hashlib.sha256(json.dumps(payload, sort_keys=True, ensure_ascii=False, default=str,
                                       separators=(',', ':')).encode()).hexdigest()
    if digest != wrapper['sha256'] or payload.get('format') != 'wallet-monitor-2' or payload.get('version') != 1:
        raise LedgerError('Backup non valido o integrità compromessa.')
    records = payload['transactions']
    if not isinstance(records, list) or len(records) > 100000:
        raise LedgerError('Dimensione backup non valida.')
    ids = [int(r['id']) for r in records]
    if len(ids) != len(set(ids)):
        raise LedgerError('ID duplicati nel backup.')
    cleaned = []
    for record in records:
        cleaned.append({**_normalize(record), 'id': int(record['id']), 'deleted': int(record['deleted']),
                        'created_at': record['created_at'], 'updated_at': record['updated_at']})
    calculate(cleaned)
    targets = payload.get('allocation_targets', [])
    if not isinstance(targets, list):
        raise LedgerError('Obiettivi nel backup non validi.')
    for target in targets:
        v = Decimal(str(target['target_pct']))
        if not v.is_finite() or v < 0 or v > 100:
            raise LedgerError('Percentuale obiettivo non valida.')
    with engine.begin() as con:
        if engine.dialect.name == 'postgresql':
            con.execute(text('SELECT pg_advisory_xact_lock(7142026)'))
        con.execute(text('DELETE FROM allocation_targets'))
        con.execute(text('DELETE FROM audit_log'))
        con.execute(text('DELETE FROM transactions'))
        for item in cleaned:
            con.execute(text('''INSERT INTO transactions
                (id,portfolio,ticker,label,kind,trade_date,quantity,unit_price,currency,fx_eur,fee,notes,broker,deleted,created_at,updated_at)
                VALUES (:id,:portfolio,:ticker,:label,:kind,:trade_date,:quantity,:unit_price,:currency,:fx_eur,:fee,:notes,:broker,:deleted,:created_at,:updated_at)'''), item)
        # Original audit log is preserved if structurally valid.
        for a in payload.get('audit_log', []):
            con.execute(text('''INSERT INTO audit_log (id,entry_id,action,previous_json,next_json,changed_at,actor)
                VALUES (:id,:entry_id,:action,:previous_json,:next_json,:changed_at,:actor)'''), a)
        for target in targets:
            con.execute(text('INSERT INTO allocation_targets (portfolio,ticker,currency,broker,target_pct) VALUES (:portfolio,:ticker,:currency,:broker,:target_pct)'), target)
        if engine.dialect.name == 'postgresql':
            con.execute(text("SELECT setval(pg_get_serial_sequence('transactions','id'), GREATEST((SELECT COALESCE(MAX(id),0) FROM transactions),1), (SELECT COUNT(*)>0 FROM transactions))"))
            con.execute(text("SELECT setval(pg_get_serial_sequence('audit_log','id'), GREATEST((SELECT COALESCE(MAX(id),0) FROM audit_log),1), (SELECT COUNT(*)>0 FROM audit_log))"))
    return len(cleaned)
